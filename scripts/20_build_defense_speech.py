def _font(run, size=14, bold=False, italic=False, color=INK):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    for a in ("w:ascii", "w:hAnsi", "w:cs"):
        rfonts.set(qn(a), FONT)


def body(doc, *runs, after=6, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, size=14):
    """runs: either a single string, or (text, bold) tuples."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.space_after = Pt(after)
    pf.space_before = Pt(0)
    pf.alignment = align
    if indent:
        pf.first_line_indent = Cm(0.75)
    for r in runs:
        if isinstance(r, tuple):
            _font(p.add_run(r[0]), size=size, bold=r[1])
        else:
            _font(p.add_run(r), size=size)
    return p


def h1(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.keep_with_next = True
    _font(p.add_run(text), size=14, bold=True, color=ACCENT)
    return p


def gloss(doc, term, text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    pf.space_after = Pt(4)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    _font(p.add_run(term + " — "), size=13, bold=True, color=ACCENT)
    _font(p.add_run(text), size=13)
    return p


def center(doc, text, size, bold=False, italic=False, color=INK, after=2):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(after)
    _font(p.add_run(text), size=size, bold=bold, italic=italic, color=color)
    return p


